/** "PDF ושיתוף": §6.2's row with the PDF (W3); with W1's share sheet and no
 *  PDF yet, its link and device printing; before W, today's link share. */
function shareRow(f: Flags, devicePrint: boolean): string {
  if (f.pdf) return "״שיתוף״ ואז ״קובץ PDF״: קובץ עם מספרי עמודים, עמוד שער ותוכן עניינים, לשליחה בוואטסאפ. ״הדפסה מהמכשיר״ עובדת גם בלי שרת.";
  if (devicePrint) return "״שיתוף״ ואז ״קישור לסיכום״: נפתח רק לחברי הקבוצה. ״הדפסה מהמכשיר״ עובדת גם בלי שרת.";
  return "״שיתוף״ שולח קישור לסיכום. קישור לסיכום נפתח רק לחברי הקבוצה.";
}

const join = (...parts: Array<string | false>) => parts.filter((p): p is string => Boolean(p)).join(" ");

/** "היום"'s help line: the meeting design's §8.2 words, with the queue's rows
 *  as this build has them (shared/study/today.ts's table and constants). */
function todayHelp(f: Flags): string {
  const rows = [
    f.cardsReview && "כרטיסיות שהגיע זמנן",
    f.quiz && "טעויות מהמבחן הקבוצתי",
    f.progress && "טעות ׳על בטוח׳ בניסוח חדש",
    f.meeting && "פסקאות שסימנת ׳לא ברור׳",
    f.var && "עדכונים בסיכום",
  ].filter((x): x is string => Boolean(x));
  const list = rows.length > 1 ? `${rows.slice(0, -1).join(", ")} ו${rows[rows.length - 1]}` : rows[0];
  const queue = `״התור שלי״ לפי הזמן שיש (${MINUTES.slice(0, -1).join(", ")} או ${MINUTES[MINUTES.length - 1]} דקות)${list ? `: ${list}` : ""}.`;
  return join(
    f.meeting ? `המסך הראשון: הפגישה של היום, ומתחת ${queue}` : `המסך הראשון: ${queue}`,
    "מה שלא נכנס עובר למחר.",
    `מ-${FLAME_LIT} ימי למידה מתוך ${FLAME_WINDOW} יש סימון. הכול גלוי רק לך.`,
    // T-2 (decision 3 of 17 Nov 2026: open early, with the member's own meter)
    f.needsMe &&
      `״הקבוצה צריכה אותך״ (כבוי עד שמפעילים אותו ב״שלי״): שאלה פתוחה שנשאלה בקבוצה מגיעה אליך כשענית נכון על ${masteryWords()} לפחות בנושא שלה, ורק את מי שנבחרו היא מגיעה. עד אז כתוב כמה תשובות נכונות חסרות לנושא הבא.`,
    f.eve && f.groupPlan && "יומיים לפני המבחן של התוכנית מופיע ״הלילה שלפני״: השקף המסכם, האסוציאציות והטעויות ׳על בטוח׳ שלך, לכל הרצאה, עם הדפסה.",
  );
}

