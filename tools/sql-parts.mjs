#!/usr/bin/env node
// supabase/study-schema.sql in 12 parts, for Supabase's SQL Editor, which
// does not take the whole file (about 0.9 MB) in one paste.
//
//   npm run sql:parts            writes supabase/parts/1.sql … 12.sql
//   node tools/sql-parts.mjs --check   exits 1 if those files are not what
//                                      the schema makes now (a unit test
//                                      runs this check)
//
// The parts are the file itself, cut only between its sections (the
// "-- ════ BEGIN SECTION X" lines, which are top-level comments) or at a
// section's own "-- ════ SECTION X CONTINUES · X n" line, so running
// parts 1 to 12 in order, each to the end, does exactly what running the
// whole file does. Every part is safe to run again, as the file is.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join } from "node:path";

const root = fileURLToPath(new URL("..", import.meta.url));
const SCHEMA = join(root, "supabase", "study-schema.sql");
const DIR = join(root, "supabase", "parts");

/** Each part after the first starts at this section. Sections added later
 *  go into the part of the section before them. Supabase's SQL Editor
 *  refuses a run much larger than about 170 KB, so each part stays at or
 *  under PART_MAX_BYTES (server/study/sqlParts.test.ts checks it). Part 10
 *  starts at L (practice sets): with I and R, part 9 would pass 170 KB.
 *  Section O (uploaded sheets) followed L in part 10 until its version 2
 *  (the sheet reader, open and numeric forms) took part 10 past 170 KB:
 *  O starts part 11. */
const STARTS = ["Q", "Z", "C", "P", "V", "H", "S", "I", "L", "O", "O 3"];
/** A part starts at a section's BEGIN line, or, for an entry such as
 *  "O 3", at the "-- ════ SECTION O CONTINUES · O 3 " line inside it: O 3
 *  (similar questions) would take part 11 past 170 KB, so the section goes
 *  on in part 12 (both run in order; the section's registry line for O 3 is
 *  at the end of part 12). */
const marker = (s) => (/^\w+$/.test(s) ? `-- ════ BEGIN SECTION ${s} ` : `-- ════ SECTION ${s.split(" ")[0]} CONTINUES · ${s} `);

/** 170,000 bytes, not 170 × 1024: whichever way the editor counts "170 KB",
 *  a part under this runs. */
export const PART_MAX_BYTES = 170_000;

export function sqlParts(text) {
  const lines = text.split("\n");
  const cuts = STARTS.map((s) => {
    const i = lines.findIndex((l) => l.startsWith(marker(s)));
    if (i < 0) throw new Error(`study-schema.sql has no "${marker(s).trim()}" line`);
    return i;
  });
  for (let k = 1; k < cuts.length; k++) if (cuts[k] <= cuts[k - 1]) throw new Error(`section ${STARTS[k]} comes before ${STARTS[k - 1]}`);
  const bounds = [0, ...cuts, lines.length];
  const n = bounds.length - 1;
  return Array.from({ length: n }, (_, k) => {
    const body = lines.slice(bounds[k], bounds[k + 1]).join("\n");
    const sections = [...body.matchAll(/^-- ════ BEGIN SECTION (\w+) /gm)].map((m) => m[1]);
    const goesOn = /^-- ════ SECTION (\w+) CONTINUES · (\w+ \d+) /.exec(body);
    const what = goesOn && !sections.length ? `section ${goesOn[1]}, continued: ${goesOn[2]}` : `${sections.length === 1 ? "section" : "sections"} ${sections.join(", ")}`;
    const head =
      `-- ═══ study-schema.sql, part ${k + 1} of ${n} (${k === 0 ? "the start, " : ""}${what}) ═══\n` +
      `-- Generated by tools/sql-parts.mjs from supabase/study-schema.sql; do not edit.\n` +
      `-- Run parts 1 to ${n} in order, each to the end, in Supabase → SQL Editor.\n` +
      (k === n - 1 ? "" : `-- Next: part ${k + 2}.\n`) +
      "\n";
    // Every part ends with a newline, as the file's lines did.
    return head + body + (body.endsWith("\n") ? "" : "\n");
  });
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const parts = sqlParts(readFileSync(SCHEMA, "utf8"));
  const name = (k) => join(DIR, `${k + 1}.sql`);
  if (process.argv.includes("--check")) {
    const stale = parts.map((p, k) => (existsSync(name(k)) && readFileSync(name(k), "utf8") === p ? null : `${k + 1}.sql`)).filter(Boolean);
    const extra = existsSync(DIR) ? readdirSync(DIR).filter((f) => /\.sql$/.test(f) && !parts.some((_, k) => f === `${k + 1}.sql`)) : [];
    if (stale.length || extra.length) {
      console.error(`supabase/parts is out of date (${[...stale, ...extra].join(", ")}): run npm run sql:parts`);
      process.exit(1);
    }
    console.log(`ok: supabase/parts matches study-schema.sql (${parts.length} parts)`);
  } else {
    mkdirSync(DIR, { recursive: true });
    parts.forEach((p, k) => writeFileSync(name(k), p));
    for (const [k, p] of parts.entries()) console.log(`supabase/parts/${k + 1}.sql  ${Buffer.byteLength(p).toLocaleString("en")} bytes  ${p.split("\n", 1)[0].replace(/^-- ═══ |═══$/g, "").trim()}`);
  }
}
